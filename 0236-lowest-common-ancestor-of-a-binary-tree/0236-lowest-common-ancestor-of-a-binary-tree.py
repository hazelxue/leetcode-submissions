# Definition for a binary tree node.
# class TreeNode(object):
#     def __init__(self, x):
#         self.val = x
#         self.left = None
#         self.right = None

class Solution(object):
    def lowestCommonAncestor(self, root, p, q):
        """
        :type root: TreeNode
        :type p: TreeNode
        :type q: TreeNode
        :rtype: TreeNode
        """
        def dfs(node):
            # end case
            if not node:
                return
            if node == p or node == q:
                return node

            # l r m
            l = dfs(node.left)
            r = dfs(node.right)
            if l and r:
                return node
            return l or r
        
        return dfs(root)

