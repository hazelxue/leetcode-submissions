class TrieNode(object):
    def __init__(self):
        self.children = {} #char -> trienode
        self.is_end = False

class Trie(object):

    def __init__(self):
        self.root = TrieNode()

    def insert(self, word):
        """
        :type word: str
        :rtype: None
        """
        node = self.root
        for ch in word:
            if ch not in node.children:
                node.children[ch] = TrieNode()
            node = node.children[ch]
        node.is_end = True
    
    def find(self, word):
        node = self.root
        for ch in word:
            if ch not in node.children:
                return None
            node = node.children[ch]
        return node

    def search(self, word):
        """
        :type word: str
        :rtype: bool
        """
        node = self.find(word)
        return node is not None and node.is_end


    def startsWith(self, prefix):
        """
        :type prefix: str
        :rtype: bool
        """
        return self.find(prefix) is not None


