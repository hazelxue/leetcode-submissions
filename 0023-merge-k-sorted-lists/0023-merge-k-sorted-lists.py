# Definition for singly-linked list.
# class ListNode(object):
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution(object):
    def mergeKLists(self, lists):
        """
        :type lists: List[Optional[ListNode]]
        :rtype: Optional[ListNode]
        """
        queue = lists
        while len(queue) > 1:
            nxt = []
            for i in range(0, len(queue), 2):
                l1 = queue[i]
                l2 = queue[i + 1] if i + 1 < len(queue) else None
                nxt.append(self.merge2lists(l1, l2))
            queue = nxt
        return queue[0] if queue else None
    
    def merge2lists(self, l1, l2):
        dummy = ListNode()
        cur = dummy
        while l1 and l2:
            if l1.val < l2.val:
                cur.next = l1
                l1 = l1.next
            else:
                cur.next = l2
                l2 = l2.next
            cur = cur.next
        cur.next = l1 or l2
        return dummy.next

