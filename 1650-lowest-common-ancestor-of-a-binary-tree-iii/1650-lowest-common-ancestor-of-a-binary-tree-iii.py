"""
# Definition for a Node.
class Node:
    def __init__(self, val):
        self.val = val
        self.left = None
        self.right = None
        self.parent = None
"""

class Solution(object):
    def lowestCommonAncestor(self, p, q):
        """
        :type node: Node
        :rtype: Node
        """
        seen = set()
        while p:
            seen.add(p)
            p = p.parent
        while q not in seen:
            q = q.parent
        return q

