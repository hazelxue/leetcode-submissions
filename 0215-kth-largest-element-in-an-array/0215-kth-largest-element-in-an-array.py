class Solution(object):
    def findKthLargest(self, nums, k):
        """
        :type nums: List[int]
        :type k: int
        :rtype: int
        """
        heap = []
        for n in nums:
            if len(heap) < k:
                heapq.heappush(heap, n)
            elif heap and heap[0] < n:
                heapq.heapreplace(heap, n)
        return heap[0]

