# Definition for a binary tree node.
# class TreeNode(object):
#     def __init__(self, val=0, left=None, right=None):
#         self.val = val
#         self.left = left
#         self.right = right
class Solution(object):
    def kthSmallest(self, root, k):
        """
        :type root: Optional[TreeNode]
        :type k: int
        :rtype: int
        """
        res = []
        def dfs(node):
            if not node or len(res) == k:
                return
            dfs(node.left)
            if len(res) == k:
                return
            res.append(node.val)
            dfs(node.right)
        dfs(root)
        return res[-1]

