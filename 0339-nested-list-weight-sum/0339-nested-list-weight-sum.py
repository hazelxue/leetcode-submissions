class Solution(object):
    def depthSum(self, nestedList):
        """
        :type nestedList: List[NestedInteger]
        :rtype: int
        """
        total = 0
        level = 1
        q = deque(nestedList)
        while q:
            for i in range(len(q)):
                tmp = q.popleft()
                if tmp.isInteger():
                    total += tmp.getInteger() * level
                else:
                    q.extend(tmp.getList())
            level += 1
        return total

