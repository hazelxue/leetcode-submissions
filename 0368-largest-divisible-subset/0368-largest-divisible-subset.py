class Solution(object):
    def largestDivisibleSubset(self, nums):
        """
        :type nums: List[int]
        :rtype: List[int]
        """
        nums.sort()
        dp = [1] * len(nums)
        prev = [None] * len(nums)

        for i in range(1, len(nums)):
            for j in range(i):
                if nums[i] % nums[j] == 0 and dp[j] + 1 > dp[i]:
                    dp[i] = dp[j] + 1
                    prev[i] = j
        
        i = dp.index(max(dp))
        res = []
        while i is not None:
            res.append(nums[i])
            nxt = prev[i]
            i = nxt
        return res[::-1]

