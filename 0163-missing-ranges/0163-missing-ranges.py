class Solution(object):
    def findMissingRanges(self, nums, lower, upper):
        """
        :type nums: List[int]
        :type lower: int
        :type upper: int
        :rtype: List[List[int]]
        """
        res = []
        prev = lower - 1
        for i in nums + [upper + 1]:
            if i - prev >= 2:
                res.append([prev + 1, i - 1])
            prev = i
        return res

